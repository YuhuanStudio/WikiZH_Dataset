# 依長度排序，避免短詞先替換掉長詞的一部分
_PATTERN = re.compile('|'.join(
    re.escape(k) for k in sorted(TW_VOCAB, key=len, reverse=True)
))

# ============================================================
# 詞邊界護欄
# ============================================================
#
# 上面那條「依長度排序」只擋得住**白名單詞彼此**的重疊，擋不住白名單詞
# 落在一個更長的、白名單以外的詞中間：
#
#     電視|頻道   → 視頻 命中中間 → 電影片道
#     攻打|印度   → 打印 命中中間 → 攻列印度      （打印 8 次出現全是這種）
#     滑鼠|標準   → 鼠標 命中中間 → 滑滑鼠準
#     用戶|名稱   → 用戶名 命中中間 → 使用者名稱稱
#
# 判斷「這裡是不是詞的邊界」需要詞表。詞表取自維基百科自己的條目標題
# （title_words.py），與語料同源。護欄只會**取消**替換，不會製造新的替換，
# 所以詞表不完整時最差就是退回原本的行為。
_GUARD = frozenset()
_GUARD_MAXLEN = 0


def load_guard(words):
    """安裝詞邊界詞表；沒安裝的話白名單就是原本的純子字串替換"""
    global _GUARD, _GUARD_MAXLEN
    _GUARD = frozenset(words)
    _GUARD_MAXLEN = max((len(w) for w in _GUARD), default=0)


def _straddles(text, i, j):
    """[i, j) 這個命中，是否被某個詞跨過邊界壓住"""
    n = len(text)
    # 左邊有詞伸進來：起點在 i 之前，終點落在 (i, j) 之內
    for st in range(max(0, i - _GUARD_MAXLEN + 1), i):
        for en in range(i + 1, min(j, st + _GUARD_MAXLEN) + 1):
            if text[st:en] in _GUARD:
                return True
    # 右邊有詞伸出去：起點在 (i, j) 之內，終點在 j 之後
    for st in range(i + 1, j):
        for en in range(j + 1, min(n, st + _GUARD_MAXLEN) + 1):
            if text[st:en] in _GUARD:
                return True
    return False


def to_tw_vocab(text):
    """把大陸慣用詞替換成台灣慣用詞（只處理白名單內的詞）"""
    if not text:
        return text
    if not _GUARD:
        return _PATTERN.sub(lambda m: TW_VOCAB[m.group(0)], text)

    out, pos = [], 0
    while True:
        m = _PATTERN.search(text, pos)
        if not m:
            break
        i, j, word = m.start(), m.end(), m.group(0)
        if not _straddles(text, i, j):
            out.append(text[pos:i])
            out.append(TW_VOCAB[word])
            pos = j
            continue
        # 這個命中跨過詞邊界。長度排序讓最長的詞先命中，被擋下時要退回去
        # 試同一位置較短的白名單詞，否則「用戶名稱」裡的 `用戶名` 被擋掉，
        # `用戶` 就再也沒機會，結果是整個詞原封不動。
        alt = next((word[:k] for k in range(len(word) - 1, 0, -1)
                    if word[:k] in TW_VOCAB and not _straddles(text, i, i + k)), None)
        if alt:
            out.append(text[pos:i])
            out.append(TW_VOCAB[alt])
            pos = i + len(alt)
        else:
            out.append(text[pos:i + 1])
            pos = i + 1
    out.append(text[pos:])
    return ''.join(out)
