# 依長度排序，避免短詞先替換掉長詞的一部分
_PATTERN = re.compile('|'.join(
    re.escape(k) for k in sorted(TW_VOCAB, key=len, reverse=True)
))


def to_tw_vocab(text):
    """把大陸慣用詞替換成台灣慣用詞（只處理白名單內的詞）"""
    if not text:
        return text
    return _PATTERN.sub(lambda m: TW_VOCAB[m.group(0)], text)
